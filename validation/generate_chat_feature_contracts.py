"""Generate browser contracts from local authoritative Pydantic models only."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.analytics.proposal_contract import AnalysisProposalConfirm, AnalysisProposalView  # noqa: E402
from app.chat_knowledge import ChatKnowledge  # noqa: E402
from app.activity_contract import WorkspaceActivity, ActivityActionRequest, ActivityActionResult  # noqa: E402
from app.analytics.schedule_contract import ScheduleList, SchedulePreviewRequest, SchedulePreview, ScheduleSave, ScheduleAction, NoticeAck  # noqa: E402
from app.analytics.history_contract import ScheduleHistory, ScheduleComparison  # noqa: E402
from app.recovery_contract import RecoveryStatus, RecoveryRequest  # noqa: E402
from app.operations_contract import OperationsStatus  # noqa: E402


def ts(schema):
    if "$ref" in schema:
        ref = schema["$ref"]
        if not ref.startswith("#/$defs/"):
            raise ValueError("Only local model references are supported")
        return ref.rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            required = set(schema.get("required", []))
            return "{ " + " ".join(f"{key}{'' if key in required else '?'}: {ts(value)};"
                for key, value in schema["properties"].items()) + " }"
        additional = schema.get("additionalProperties", {})
        return "Record<string, " + (ts(additional) if isinstance(additional, dict) else "unknown") + ">"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null", None: "unknown"}[kind]


def generate(models):
    definitions = {}
    for model in models:
        schema = model.model_json_schema()
        for name, definition in {**schema.get("$defs", {}), model.__name__: schema}.items():
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"Conflicting model definition: {name}")
            definitions[name] = definition
    lines = ["// Generated by validation/generate_chat_feature_contracts.py; do not edit."]
    for name, definition in definitions.items():
        required = set(definition.get("required", []))
        lines.append(f"export interface {name} {{")
        for key, value in definition["properties"].items():
            lines.append(f"  {key}{'' if key in required else '?'}: {ts(value)};")
        lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    for filename, models in {
        "analysisProposal.generated.ts": [AnalysisProposalView, AnalysisProposalConfirm],
        "chatKnowledge.generated.ts": [ChatKnowledge],
        "workspaceActivity.generated.ts": [WorkspaceActivity, ActivityActionRequest, ActivityActionResult],
        "analysisSchedules.generated.ts": [ScheduleList, SchedulePreviewRequest, SchedulePreview, ScheduleSave, ScheduleAction, NoticeAck],
        "analysisHistory.generated.ts": [ScheduleHistory, ScheduleComparison],
        "recovery.generated.ts": [RecoveryStatus, RecoveryRequest],
        "operations.generated.ts": [OperationsStatus],
    }.items():
        content = generate(models)
        path = ROOT / "frontend/src" / filename
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Contract out of sync: {filename}")
        else:
            path.write_text(content, encoding="utf-8")
    print("Chat feature contracts are synchronized.")


if __name__ == "__main__":
    main()
