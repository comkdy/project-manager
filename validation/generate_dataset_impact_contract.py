"""Generate the frontend impact response types from the provider's schema."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
from app.dataset_impact_contract import DatasetImpact  # noqa: E402


def typescript(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return repr(schema['const'])
    if 'enum' in schema:
        return ' | '.join(repr(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(typescript(item) for item in schema['anyOf'])
    kind = schema['type']
    if kind == 'array':
        return f"Array<{typescript(schema['items'])}>"
    return {'string': 'string', 'integer': 'number', 'number': 'number',
            'null': 'null', 'boolean': 'boolean'}[kind]


schema = DatasetImpact.model_json_schema()
lines = ['// Generated by validation/generate_dataset_impact_contract.py; do not edit.']
for name, definition in {**schema.get('$defs', {}), 'DatasetImpact': schema}.items():
    lines.append(f'export interface {name} {{')
    for key, value in definition['properties'].items():
        optional = '' if key in definition.get('required', []) else '?'
        lines.append(f'  {key}{optional}: {typescript(value)};')
    lines.append('}')
content = '\n'.join(lines) + '\n'
target = ROOT / 'frontend/src/datasetImpact.generated.ts'
if '--check' in sys.argv:
    if not target.exists() or target.read_text(encoding='utf-8') != content:
        raise SystemExit('Dataset impact types differ from the provider contract. Regenerate them.')
else:
    target.write_text(content, encoding='utf-8')
print('Dataset impact contract is synchronized.')
